"""Evidence bundles — what an auditor actually receives.

A zip that verifies *without the producer's server* (the Enzai/Credo
pattern): the events, a manifest with the chain head and Merkle seal, the
policy snapshot that governed the session, the signer's public key, a
human-readable report, and a standalone verifier script. Verification that
requires trusting the system being audited is not verification.
"""

from __future__ import annotations

import io
import json
import zipfile
from typing import Any

from . import __version__
from .chain import verify_events
from .events import now_utc

STANDALONE_VERIFIER = '''#!/usr/bin/env python3
"""Standalone AgentTrail bundle verifier — needs: pip install jcs cryptography.
Recomputes the hash chain and Ed25519 signatures from events.jsonl alone."""
import base64, hashlib, json, sys, zipfile
import jcs
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from cryptography.hazmat.primitives import serialization

def canon(o): return jcs.canonicalize(o)
def h(b): return "sha256:" + hashlib.sha256(b).hexdigest()

def main(path):
    z = zipfile.ZipFile(path)
    names = set(z.namelist())
    events = [json.loads(l) for l in z.read("events.jsonl").decode().splitlines() if l.strip()]
    manifest = json.loads(z.read("manifest.json"))
    sid = manifest["session_id"]
    pub_b64 = z.read("signer_public_key.b64").decode().strip()
    pub = Ed25519PublicKey.from_public_bytes(base64.b64decode(pub_b64))
    prev = h(b"agenttrail:genesis:" + sid.encode())
    for i, ev in enumerate(events):
        if ev.get("sequence_no") != i:
            print(f"FAIL: sequence gap at {i}"); return 1
        integ = ev.get("integrity") or {}
        if integ.get("prev_hash") != prev:
            print(f"FAIL: prev_hash mismatch at sequence {i}"); return 1
        unsigned = {k: v for k, v in ev.items() if k != "integrity"}
        prev_bytes = bytes.fromhex(prev.split(":", 1)[1])
        digest = h(prev_bytes + canon(unsigned))
        if digest != integ.get("event_hash"):
            print(f"FAIL: event_hash mismatch at sequence {i} — payload modified after sealing"); return 1
        try:
            pub.verify(base64.b64decode(integ["signature"]), bytes.fromhex(digest.split(":", 1)[1]))
        except Exception:
            print(f"FAIL: bad signature at sequence {i}"); return 1
        prev = digest
    print(f"OK: {len(events)} events verified for session {sid}; head {prev[:19]}...")
    if "seal.json" in names:
        print("Seal present in manifest:", manifest.get("seal", {}).get("status"))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "bundle.zip"))
'''


def _report_md(session_id: str, events: list[dict[str, Any]],
               verification: dict[str, Any]) -> str:
    lines = [
        f"# AgentTrail evidence report — session {session_id}",
        "",
        f"Events: {len(events)} · Chain valid: {verification.get('valid')} · "
        f"Seal: {(verification.get('seal') or {}).get('status', 'n/a')}",
        "",
        "| # | Time (UTC) | Event | Key detail |",
        "|---|---|---|---|",
    ]
    for ev in events:
        detail = ""
        if ev.get("tool"):
            detail = ev["tool"]["tool_name"]
            if ev["tool"].get("action_id"):
                detail += f" ({ev['tool']['action_id']} v{ev['tool'].get('action_version')})"
        if ev.get("policy"):
            detail += f" — policy: {ev['policy']['verdict']} / {ev['policy']['reason_code']}"
        if ev.get("outcome"):
            detail += f" — outcome: {ev['outcome']['status']}"
            if ev["outcome"].get("downstream_receipt"):
                detail += f", receipt {ev['outcome']['downstream_receipt']}"
        if ev.get("approval") and ev["approval"].get("approver"):
            detail += f" — approver: {ev['approval']['approver']}"
        lines.append(f"| {ev['sequence_no']} | {ev['event_time_utc']} | "
                     f"{ev['event_type']} | {detail} |")
    lines += ["", "Generated by AgentTrail. Verify offline: "
              "`python verify_bundle.py this-bundle.zip`"]
    return "\n".join(lines) + "\n"


def build_bundle(store, session_id: str, verification: dict[str, Any],
                 policy_snapshot: dict[str, Any]) -> bytes:
    events = store.session_events(session_id)
    key_ids = sorted({ev["integrity"]["signer_key_id"] for ev in events})
    manifest = {
        "format": "agenttrail-evidence-bundle/1",
        "agenttrail_version": __version__,
        "session_id": session_id,
        "generated_at": now_utc(),
        "event_count": len(events),
        "head_hash": verification.get("head_hash"),
        "seal": verification.get("seal"),
        "verification_at_export": verification,
        "canonicalization": "RFC 8785 (JSON Canonicalization Scheme)",
        "hash_chain": "event_hash = SHA-256(prev_hash_bytes || canonical event); "
                      "genesis prev_hash = SHA-256('agenttrail:genesis:' || session_id)",
        "signers": key_ids,
    }
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("events.jsonl",
                   "\n".join(json.dumps(ev, sort_keys=True) for ev in events) + "\n")
        z.writestr("manifest.json", json.dumps(manifest, indent=2))
        z.writestr("policy_snapshot.json", json.dumps(policy_snapshot, indent=2))
        z.writestr("report.md", _report_md(session_id, events, verification))
        z.writestr("verify_bundle.py", STANDALONE_VERIFIER)
        for kid in key_ids:
            pub = store.signer_public_key(kid)
            if pub:
                z.writestr("signer_public_key.b64", pub)
                z.writestr(f"signers/{kid}.b64", pub)
    return buf.getvalue()


def verify_bundle_bytes(data: bytes) -> dict[str, Any]:
    """Verify a bundle zip in-process (same math as the standalone script)."""
    z = zipfile.ZipFile(io.BytesIO(data))
    events = [json.loads(line) for line in
              z.read("events.jsonl").decode().splitlines() if line.strip()]
    manifest = json.loads(z.read("manifest.json"))
    public_keys = {}
    for name in z.namelist():
        if name.startswith("signers/") and name.endswith(".b64"):
            public_keys[name[len("signers/"):-len(".b64")]] = z.read(name).decode().strip()
    if not public_keys and "signer_public_key.b64" in z.namelist():
        kid = (events[0].get("integrity") or {}).get("signer_key_id")
        public_keys[kid] = z.read("signer_public_key.b64").decode().strip()
    result = verify_events(events, manifest["session_id"], public_keys)
    result["session_id"] = manifest["session_id"]
    return result
